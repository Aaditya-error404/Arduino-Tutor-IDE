// Generates clean, procedural OpenSCAD code with CSG booleans
function generateOpenScadScript(shapes: CadShape[], projectName: string): string {
  const visible = shapes.filter((s) => s.visible);
  const solids = visible.filter((s) => s.mode === 'solid');
  const holes = visible.filter((s) => s.mode === 'hole');

  let code = `// ========================================================\n`;
  code += `// Project: ${projectName || 'SparkByte 3D Model'}\n`;
  code += `// Generated by SparkByte 3D CAD Studio · Aaditya Joshi\n`;
  code += `// ========================================================\n\n`;
  code += `$fn = 64; // High-resolution polygon arcs\n\n`;

  const renderShapeCall = (s: CadShape) => {
    let inner = '';
    switch (s.type) {
      case 'cube':
        inner = `cube([${s.dimensions.width}, ${s.dimensions.depth}, ${s.dimensions.height}], center = true);`;
        break;
      case 'cylinder':
      case 'hole':
        inner = `cylinder(r = ${s.dimensions.radius}, h = ${s.dimensions.height}, center = true);`;
        break;
      case 'sphere':
        inner = `sphere(r = ${s.dimensions.radius});`;
        break;
      case 'cone':
        inner = `cylinder(r1 = ${s.dimensions.radius}, r2 = ${s.dimensions.radiusTop || 0}, h = ${s.dimensions.height}, center = true);`;
        break;
      case 'torus':
        inner = `rotate_extrude() translate([${s.dimensions.radius}, 0, 0]) circle(r = ${s.dimensions.innerRadius || 3});`;
        break;
    }

    const hasRot = s.rotation[0] !== 0 || s.rotation[1] !== 0 || s.rotation[2] !== 0;
    const hasTrans = s.position[0] !== 0 || s.position[1] !== 0 || s.position[2] !== 0;

    let res = inner;
    if (hasRot) {
      res = `rotate([${s.rotation[0]}, ${s.rotation[1]}, ${s.rotation[2]}]) ${res}`;
    }
    if (hasTrans) {
      res = `translate([${s.position[0]}, ${s.position[1]}, ${s.position[2]}]) ${res}`;
    }
    return `    // ${s.name}\n    ${res}`;
  };

  if (holes.length === 0) {
    code += `union() {\n`;
    for (const s of solids) {
      code += `${renderShapeCall(s)}\n`;
    }
    code += `}\n`;
  } else {
    code += `difference() {\n`;
    code += `  // Positive Solids\n`;
    code += `  union() {\n`;
    for (const s of solids) {
      code += `  ${renderShapeCall(s)}\n`;
    }
    code += `  }\n\n`;
    code += `  // Subtractive Holes (Negative Cutters)\n`;
    for (const h of holes) {
      code += `${renderShapeCall(h)}\n`;
    }
    code += `}\n`;
  }

  return code;
}

